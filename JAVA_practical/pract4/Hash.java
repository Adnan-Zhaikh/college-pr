package JAVA_practical.pract4;
import java.util.*;

public class Hash {
    public static void main(String[] args) {
        Set<String> names = new HashSet<>();
        names.add("Farhan");
        names.add("Gyani");
        names.add("Nitin");
    

    for (String name : names){
        System.out.println(name);
    }
}
}
